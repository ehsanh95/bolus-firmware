static void MacGetUniqueId(uint8_t *id)
{
    uint32_t uid0;
    uint32_t uid1;
    uint32_t uid2;

    if (id == NULL)
    {
        return;
    }

    uid0 = HAL_GetUIDw0();
    uid1 = HAL_GetUIDw1();
    uid2 = HAL_GetUIDw2();

    id[0] = (uint8_t)(uid2 >> 24);
    id[1] = (uint8_t)(uid2 >> 16);
    id[2] = (uint8_t)(uid2 >> 8);
    id[3] = (uint8_t)uid2;
    uid0 ^= uid1;
    id[4] = (uint8_t)(uid0 >> 24);
    id[5] = (uint8_t)(uid0 >> 16);
    id[6] = (uint8_t)(uid0 >> 8);
    id[7] = (uint8_t)uid0;
}

