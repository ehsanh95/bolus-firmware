/*
 * ============================================================
 * [UNTESTED] LoRaWAN ABP uplink + downlink integration staging
 * ============================================================
 * The I-CUBE-LRWAN stack in this repository is configured for EU868,
 * Class A and LoRaWAN 1.0.3 crypto. No OTAA join request is issued here.
 * Gateway/TTN validation is still required after this change.
 *
 * Downlink command acceptance must not be interpreted as live hardware apply;
 * see downlink_management_diag.pending_apply_mask.
 */

#define LORAWAN_UPLINK_BUSY_RETRY_MS       100UL
#define LORAWAN_ABP_LRWAN_VERSION_V103     0x01000300UL

typedef struct
{
    bool valid;
    uint8_t size;
    uint8_t attempts;
    uint16_t sequence;
    uint8_t payload[BOLUS_LORAWAN_MAX_APP_PAYLOAD];
} lorawan_uplink_queue_entry_t;

typedef enum
{
    LORAWAN_TX_KIND_NONE = 0,
    LORAWAN_TX_KIND_TELEMETRY,
    LORAWAN_TX_KIND_CONTROL_RESPONSE
} lorawan_tx_kind_t;

static lorawan_uplink_queue_entry_t s_queue[BOLUS_LORAWAN_QUEUE_DEPTH];
static uint8_t s_queue_head = 0U;
static uint8_t s_queue_tail = 0U;
static uint8_t s_queue_count = 0U;

/*
 * One dedicated priority slot for ACK/NACK generated by a received downlink.
 * It is intentionally separate from the telemetry queue so an RX1/RX2 command
 * response cannot corrupt or pop the telemetry head currently awaiting MCPS
 * confirmation.
 */
static bool s_control_response_pending = false;
static uint8_t s_control_response_size = 0U;
static uint8_t s_control_response_attempts = 0U;
static uint8_t s_control_response[DOWNLINK_MANAGEMENT_RESPONSE_SIZE] = {0};

static bool s_initialized = false;
static bool s_joined = false;
static bool s_tx_in_flight = false;
static lorawan_tx_kind_t s_tx_kind = LORAWAN_TX_KIND_NONE;
static uint32_t s_next_action_tick_ms = 0U;
static uint32_t s_retry_delay_ms = 2000U;
static uint8_t s_max_tx_attempts = 3U;

static uint8_t s_f_nwk_s_int_key[16] = BOLUS_LORAWAN_F_NWK_S_INT_KEY_BYTES;
static uint8_t s_s_nwk_s_int_key[16] = BOLUS_LORAWAN_S_NWK_S_INT_KEY_BYTES;
static uint8_t s_app_s_key[16] = BOLUS_LORAWAN_APP_S_KEY_BYTES;

/*
 * LoRaMacInitialization stores these pointers in MacCtx and uses them later
 * from TxDone/RxDone and MCPS/MLME processing. They therefore must have static
 * lifetime; stack-local instances become invalid as soon as Init returns and
 * can turn a later TxDone callback into a HardFault.
 */
static LoRaMacPrimitives_t s_mac_primitives;
static LoRaMacCallback_t s_mac_callbacks;

lorawan_uplink_diag_t lorawan_uplink_service_diag = {0};

static bool TimeReached(uint32_t now_ms, uint32_t deadline_ms)
{
    return ((int32_t)(now_ms - deadline_ms) >= 0);
}

static lorawan_uplink_queue_entry_t *QueueHead(void)
{
    if (s_queue_count == 0U)
    {
        return NULL;
    }

    return &s_queue[s_queue_head];
}

static void QueuePop(void)
{
    if (s_queue_count == 0U)
    {
        return;
    }

    memset(&s_queue[s_queue_head], 0, sizeof(s_queue[s_queue_head]));
    s_queue_head = (uint8_t)((s_queue_head + 1U) % BOLUS_LORAWAN_QUEUE_DEPTH);
    s_queue_count--;
    lorawan_uplink_service_diag.queue_count = s_queue_count;
}

